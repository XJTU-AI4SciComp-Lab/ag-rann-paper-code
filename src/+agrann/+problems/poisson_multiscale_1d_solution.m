function z = poisson_multiscale_1d_solution(x, n_sol)
%POISSON_MULTISCALE_1D_SOLUTION Exact 1-D multiscale Poisson solution.

switch n_sol
    case 1
        z=sin(2^1*pi*x);
    case 2
        z=(sin(2^1*pi*x)+...
           sin(2^2*pi*x))/2;
    case 3
        z=(sin(2^1*pi*x)+...
           sin(2^2*pi*x)+...
           sin(2^3*pi*x))/3;
    case 4
        z=(sin(2^1*pi*x)+...
           sin(2^2*pi*x)+...
           sin(2^3*pi*x)+...
           sin(2^4*pi*x))/4;
    case 5
        z=(sin(2^1*pi*x)+...
           sin(2^2*pi*x)+...
           sin(2^3*pi*x)+...
           sin(2^4*pi*x)+...
           sin(2^5*pi*x))/5;
    case 6
        z=(sin(2^1*pi*x)+...
           sin(2^2*pi*x)+...
           sin(2^3*pi*x)+...
           sin(2^4*pi*x)+...
           sin(2^5*pi*x)+...
           sin(2^6*pi*x))/6;
end
end
