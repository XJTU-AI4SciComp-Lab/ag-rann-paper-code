function z = poisson_multiscale_1d_forcing(x, n_sol)
%POISSON_MULTISCALE_1D_FORCING Right-hand side for the 1-D multiscale case.

switch n_sol
    case 1
        z = (2^1*pi)^2*sin(2^1*pi*x);
    case 2
        z = ((2^1*pi)^2*sin(2^1*pi*x)+...
               (2^2*pi)^2*sin(2^2*pi*x))/2;
    case 3
        z = ((2^1*pi)^2*sin(2^1*pi*x)+...
               (2^2*pi)^2*sin(2^2*pi*x)+...
               (2^3*pi)^2*sin(2^3*pi*x))/3;
    case 4
        z = ((2^1*pi)^2*sin(2^1*pi*x)+...
               (2^2*pi)^2*sin(2^2*pi*x)+...
               (2^3*pi)^2*sin(2^3*pi*x)+...
               (2^4*pi)^2*sin(2^4*pi*x))/4;
    case 5
        z = ((2^1*pi)^2*sin(2^1*pi*x)+...
               (2^2*pi)^2*sin(2^2*pi*x)+...
               (2^3*pi)^2*sin(2^3*pi*x)+...
               (2^4*pi)^2*sin(2^4*pi*x)+...
               (2^5*pi)^2*sin(2^5*pi*x))/5;
    case 6
        z = ((2^1*pi)^2*sin(2^1*pi*x)+...
               (2^2*pi)^2*sin(2^2*pi*x)+...
               (2^3*pi)^2*sin(2^3*pi*x)+...
               (2^4*pi)^2*sin(2^4*pi*x)+...
               (2^5*pi)^2*sin(2^5*pi*x)+...
               (2^6*pi)^2*sin(2^6*pi*x))/6;
end
end
